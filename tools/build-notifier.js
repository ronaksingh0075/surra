// Build the Surra notifier into one Apps Script file: notifier/dist/Code.gs (paste it into the Apps Script editor).
// Layout: polyfills, the bundled crypto library (SurraCrypto), the journey's stop order and city names, the notifier.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const esbuild = require('esbuild');

const ROOT = path.join(__dirname, '..');
const N = path.join(ROOT, 'notifier');
// Apps Script's V8 runs modern JavaScript, but play safe with newer syntax: esbuild rewrites it into older forms
// (target es2020 already rewrites class fields, private fields and other later additions; BigInt stays native)
const supported = { 'optional-chain': false, 'nullish-coalescing': false };
const opts = { target: 'es2020', supported, legalComments: 'none', charset: 'utf8' };

(async () => {
  const lib = await esbuild.build({ ...opts, entryPoints: [path.join(N, 'src/crypto.js')], bundle: true, format: 'iife', globalName: 'SurraCrypto', minify: true, write: false, platform: 'neutral', mainFields: ['module', 'main'] });
  const libJs = lib.outputFiles[0].text.trim();
  const poly = (await esbuild.transform(fs.readFileSync(path.join(N, 'src/polyfill.js'), 'utf8'), opts)).code.trim();
  const main = (await esbuild.transform(fs.readFileSync(path.join(N, 'src/main.js'), 'utf8'), opts)).code.trim();
  // stop order and city names straight from the curriculum
  const ctx = {}; vm.createContext(ctx);
  vm.runInContext(['data_a.js', 'data_b.js'].map(f => fs.readFileSync(path.join(ROOT, 'src', f), 'utf8')).join('\n') + '\n;this.LEVELS=LEVELS;this.STOPS=STOPS;', ctx);
  const ORDER = ctx.LEVELS.flatMap(l => l.stops), CITY = Object.fromEntries(ORDER.map(s => [s, ctx.STOPS[s].city]));
  // road distances, safehouses and the stake rules from the app's own journey.js
  const journey = fs.readFileSync(path.join(ROOT, 'src/journey.js'), 'utf8');
  const lit = name => { const m = new RegExp(`const ${name} = ([\\s\\S]*?\\n?[}\\]]);`).exec(journey); if (!m) throw new Error('journey.js: no ' + name); return vm.runInNewContext('(' + m[1] + ')'); };
  const ROAD_KM = lit('ROAD_KM'), SAFEHOUSES = lit('SAFEHOUSES'), KMR = lit('KM');
  const KM_RULES = { stakeMin: KMR.stakeMin, stakeMax: KMR.stakeMax, raceStake: KMR.raceStake };
  ORDER.forEach(s => { if (!ROAD_KM[s]) throw new Error('journey.js: no road distance for ' + s); });
  const body = [
    poly,
    '// ---- crypto: @noble/curves (P-256), @noble/hashes (SHA-256, HKDF), @noble/ciphers (AES-GCM), MIT licence, paulmillr.com/noble',
    libJs,
    '// ---- the journey',
    `const ORDER = ${JSON.stringify(ORDER)};`,
    `const CITY = ${JSON.stringify(CITY)};`,
    `const ROAD_KM = ${JSON.stringify(ROAD_KM)};`,
    `const SAFEHOUSES = ${JSON.stringify(SAFEHOUSES)};`,
    `const KM_RULES = ${JSON.stringify(KM_RULES)};`,
    '',
    main,
  ].join('\n');
  const hash = crypto.createHash('sha256').update(body).digest('hex').slice(0, 10);
  const out = `// Surra notifier for Google Apps Script. Generated by tools/build-notifier.js from notifier/src (build ${hash}).\n// Paste this whole file into Code.gs in the Apps Script editor. Set-up steps: notifier/README.md\n${body}\n`;
  fs.mkdirSync(path.join(N, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(N, 'dist/Code.gs'), out);
  fs.copyFileSync(path.join(N, 'src/appsscript.json'), path.join(N, 'dist/appsscript.json'));
  console.log(`notifier/dist/Code.gs: ${(out.length / 1024).toFixed(1)} KB (build ${hash})`);
})().catch(e => { console.error(e); process.exit(1); });
